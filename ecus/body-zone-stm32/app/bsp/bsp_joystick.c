/**
 * @file    bsp_joystick.c
 * @brief   Board support: KY-023 joystick (implementation).
 *
 * Layer:   bsp (calls the ST HAL)
 * Spec:    004-joystick-indication
 * Req:     HW-ZCS-001, SW-ZCS-050 (sampling part)
 *
 * ADC1 is configured by the CubeMX-generated MX_ADC1_Init(): 12-bit, single
 * conversion, software start, channel IN1 (PA1), 84 cycles sampling time.
 * The long sampling time gives the joystick potentiometer (high source
 * impedance) enough time to charge the ADC's sample capacitor.
 * PE7 is configured as input with pull-up by MX_GPIO_Init().
 */
#include "bsp_joystick.h"

#include "stm32f4xx_hal.h"

/* Defined in Core/Src/main.c (generated by CubeMX). */
extern ADC_HandleTypeDef hadc1;

/* One conversion takes about 5 us at 21 MHz ADC clock; 1 ms is only the
 * upper bound if the ADC is stuck, so the main loop is never blocked. */
#define JOYSTICK_ADC_TIMEOUT_MS 1U

void bsp_joystick_init(void)
{
    /* Nothing to do yet: pins and ADC are set up by the generated init code.
     * Kept so the app wiring stays the same if calibration is added later. */
}

uint16_t bsp_joystick_read_x(void)
{
    uint16_t value = (uint16_t)BSP_JOYSTICK_RAW_NEUTRAL;

    if (HAL_ADC_Start(&hadc1) == HAL_OK)
    {
        if (HAL_ADC_PollForConversion(&hadc1, JOYSTICK_ADC_TIMEOUT_MS) == HAL_OK)
        {
            value = (uint16_t)HAL_ADC_GetValue(&hadc1);
        }
        (void)HAL_ADC_Stop(&hadc1);
    }

    return value;
}

bool bsp_joystick_button_raw(void)
{
    /* Active low: the pull-up holds the pin high, the button pulls it to GND. */
    return HAL_GPIO_ReadPin(GPIOE, GPIO_PIN_7) == GPIO_PIN_RESET;
}
